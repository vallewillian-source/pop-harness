#!/usr/bin/env python3
"""CI gate: fails when a Portuguese identifier survives outside the allowlist.

Sources, in order of precedence:

- `scripts/glossary-map.txt` is the dictionary (Portuguese term -> English term). Inflected forms
  are derived from it here, so plural, feminine and verb conjugation of a mapped term are caught
  without adding lines to the map.
- `scripts/allow-names.txt` is the closed exception list of section 7.2 of the refactor spec:
  flow language words, every published name (table, column, index, trigger, route, operationId,
  JSON field, poph.toml key, CLI command and flag, environment variable, metric, plugin protocol
  term, backup key), the words that are spelled the same in both languages and the example flow
  scripts, which are frozen byte by byte. The whole file is written by `--atualizar-allowlist`
  from the published inventory plus the curated list in this script, so a hand edit fails the gate.
- `scripts/pendentes-nomes.txt` is the module allowlist: one line per file that still has a
  Portuguese identifier, with the module and the count. It is generated by
  `--atualizar-pendentes` and is a ceiling per file: one extra identifier in a listed file fails
  the gate, and a listed file that became clean fails until the list is regenerated.

Identifier extraction and term splitting are imported, not copied: `scripts/glossary-terms.py`
owns the per-language token reader (which already skips string and comment by the syntax of
`scripts/strip-comments.py`) and the snake_case / camelCase / kebab-case splitter. This gate only
decides which terms are Portuguese.

Scope is what the repository publishes: the scan uses `git ls-files --cached --others
--exclude-standard`, so a file hidden by `.git/info/exclude` on one machine cannot make the gate
differ from the one a clean clone sees. Without `git`, the whole working tree is scanned. Product
text (error message, log line, prompt, screen label, test data) lives in strings and comments and
is therefore never seen here; the same goes for generated `console/src/api/schema.d.ts`.

Commands:

- `bash scripts/check-names.sh`: gate over the repository against the pending list.
- `bash scripts/check-names.sh <paths>`: check one module; prints nothing when it is clean.
- `bash scripts/check-names.sh --atualizar-pendentes`: regenerate the pending list.
- `bash scripts/check-names.sh --atualizar-allowlist`: regenerate the generated block of the
  allowlist from the published inventory.
- `bash scripts/check-names.sh --measure`: most frequent Portuguese identifiers, for maintenance.
"""

import argparse
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ALLOW_PATH = ROOT / "scripts" / "allow-names.txt"
PENDING_PATH = ROOT / "scripts" / "pendentes-nomes.txt"
MAP_PATH = ROOT / "scripts" / "glossary-map.txt"
COMMENTS_SCANNER = ROOT / "scripts" / "strip-comments.py"
GLOSSARY_TOOL = ROOT / "scripts" / "glossary-terms.py"
COMMENTS_GATE = ROOT / "scripts" / "check_comments.py"

NON_CODE_PREFIXES = ("design_assets/",)
IDENTIFIER_SHAPE = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")

GENERATED_START = "# >>> generated by --atualizar-allowlist"
GENERATED_END = "# <<< generated by --atualizar-allowlist"

ALLOW_HEADER = (
    "# Portuguese identifiers allowed in the repository: section 7.2 of the refactor spec.",
    "# Fields: kind<TAB>value<TAB>reason. Kinds: name (a whole identifier), term (a word inside an",
    "# identifier) and path (every identifier of one file). The block between the markers is",
    "# generated from the published inventory; everything above it is curated in check_names.py,",
    "# so the file is written by `bash scripts/check-names.sh --atualizar-allowlist` either way.",
)

PENDING_HEADER = (
    "# Files with a Portuguese identifier outside the allowlist: module, count and path,",
    "# separated by TAB. Generated by `bash scripts/check-names.sh --atualizar-pendentes`;",
    "# do not edit by hand.",
)

MANUAL_ENTRIES = (
    ("term", "status", "word spelled the same in Portuguese and English"),
    ("term", "total", "word spelled the same in Portuguese and English"),
    ("term", "data", "word spelled the same in Portuguese and English"),
    ("term", "final", "word spelled the same in Portuguese and English"),
    ("term", "whatsapp", "product name, spelled the same in both languages"),
    ("term", "resolve", "English word used as a method name and a Portuguese verb form"),
    ("term", "os", "word spelled the same in Portuguese and English"),
    ("term", "as", "word spelled the same in Portuguese and English"),
    ("term", "no", "word spelled the same in Portuguese and English"),
    ("term", "em", "word spelled the same in Portuguese and English"),
    ("term", "um", "word spelled the same in Portuguese and English"),
    ("term", "ja", "word spelled the same in Portuguese and English"),
    ("term", "a", "single letter, both languages"),
    ("term", "e", "single letter, both languages"),
    ("term", "o", "single letter, both languages"),
    ("term", "ou", "word spelled the same in Portuguese and English"),
    ("path", "tests/fluxos/exemplos/agendar_visita.star", "published flow language example, frozen byte by byte"),
    ("path", "tests/fluxos/exemplos/confirmar_entrega.star", "published flow language example, frozen byte by byte"),
    ("path", "tests/fluxos/exemplos/triagem_suporte.star", "published flow language example, frozen byte by byte"),
    ("path", "tests/contratos/base/flows/agendar_visita.star", "contract baseline copy of a published flow example"),
    ("path", "tests/contratos/base/flows/confirmar_entrega.star", "contract baseline copy of a published flow example"),
    ("path", "tests/contratos/base/flows/triagem_suporte.star", "contract baseline copy of a published flow example"),
)

PLURAL_ES = ("r", "z", "s")
EXTRA_PLURALS = {("ao", "oes"), ("ao", "aes"), ("ao", "aos")}
VERB_ENDINGS = {
    "ar": ("a", "am", "ou", "ei", "ando", "ado", "ada", "ados", "adas", "ava", "aram", "arem", "aria"),
    "er": ("em", "eu", "endo", "ido", "ida", "ia", "eram", "erem", "eria"),
    "ir": ("em", "iu", "indo", "ido", "ida", "ia", "iram", "irem", "iria"),
}


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    if spec is None or spec.loader is None:
        raise SystemExit(f"check-names: cannot load {path.as_posix()}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


scanner = load_module(COMMENTS_SCANNER, "strip_comments")
glossary = load_module(GLOSSARY_TOOL, "glossary_terms")
comments_gate = load_module(COMMENTS_GATE, "check_comments")


def plural_forms(term):
    if term.endswith("ao") and len(term) > 3:
        return {term[: -len(suffix)] + replacement for suffix, replacement in EXTRA_PLURALS}
    if term.endswith("l") and len(term) > 2:
        return {term[:-2] + "is"}
    if term.endswith("m") and len(term) > 2:
        return {term[:-1] + "ns"}
    if term.endswith(PLURAL_ES):
        return {term + "es"}
    return {term + "s"}


def inflected_forms(term):
    forms = {term} | plural_forms(term)
    if term.endswith("o") and len(term) > 2:
        forms.update({term[:-1] + "a", term[:-1] + "as"})
        forms.add(term[:-1] + "os")
    if term.endswith("os") and len(term) > 3:
        forms.add(term[:-2] + "as")
    for suffix, endings in VERB_ENDINGS.items():
        if term.endswith(suffix) and len(term) > len(suffix) + 2:
            stem = term[: -len(suffix)]
            forms.update(stem + ending for ending in endings)
    return {form for form in forms if len(form) >= 2}


def split_identifier(token):
    """Terms of an identifier.

    `dividir_termo` splits camelCase from the second capital on, so an all caps acronym loses all
    but its last two letters (`CASCADE` would become `de`). Tokens without a single lowercase
    letter are lowered first, which keeps them whole words.
    """
    return glossary.dividir_termo(token if any(char.islower() for char in token) else token.lower())


def read_map():
    entries = {}
    duplicates = []
    for number, line in enumerate(MAP_PATH.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        fields = line.split("\t")
        if len(fields) != 2:
            duplicates.append(f"line {number}: expected two TAB separated fields: {line!r}")
            continue
        term, english = fields[0].strip(), fields[1].strip()
        if not term or not english:
            duplicates.append(f"line {number}: empty term or translation")
            continue
        entries[term] = english
    return entries, duplicates


def build_dictionary(entries, allowed_terms):
    dictionary = {}
    for term in entries:
        for form in inflected_forms(term):
            if form in allowed_terms:
                continue
            dictionary.setdefault(form, term)
    for term in allowed_terms:
        dictionary.pop(term, None)
    return dictionary


def read_allow(path):
    manual = []
    generated = []
    inside = False
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        stripped = line.strip()
        if stripped == GENERATED_START:
            inside = True
            continue
        if stripped == GENERATED_END:
            inside = False
            continue
        if not stripped or stripped.startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 3:
            raise ValueError(f"line {number}: expected kind, value and reason separated by TAB: {line!r}")
        kind, value, reason = (field.strip() for field in fields)
        if kind not in ("name", "term", "path"):
            raise ValueError(f"line {number}: unknown kind: {kind!r}")
        if not value or not reason:
            raise ValueError(f"line {number}: empty value or reason")
        (generated if inside else manual).append((kind, value, reason))
    return manual, generated


def published_identifier_names(inventory):
    for kind, names in inventory.items():
        if kind == "linguagem_fluxos":
            continue
        for name in names:
            if IDENTIFIER_SHAPE.match(name):
                yield kind, name
                continue
            for segment in re.split(r"[./\s-]+", name):
                if segment and IDENTIFIER_SHAPE.match(segment):
                    yield kind, segment


def generated_entries(inventory):
    entries = {("name", word): "flow language word, frozen by P6" for word in inventory["linguagem_fluxos"]}
    for kind, name in published_identifier_names(inventory):
        label = f"published {kind.replace('_', ' ')}: {name}"
        entries.setdefault(("name", name), label)
    return [("name", value, reason) for (_, value), reason in entries.items()]


def render_allow(manual, generated):
    lines = list(ALLOW_HEADER)
    for kind, value, reason in manual:
        lines.append(f"{kind}\t{value}\t{reason}")
    lines.append(GENERATED_START)
    for kind, value, reason in sorted(generated, key=lambda entry: (entry[0], entry[1].lower())):
        lines.append(f"{kind}\t{value}\t{reason}")
    lines.append(GENERATED_END)
    return "\n".join(lines) + "\n"


def repository_paths():
    return glossary.caminhos_do_repositorio()


def collect_hits(state, paths, visible):
    dirty = {}
    findings = []
    seen_tokens = {}
    resolved = [Path(entry) if Path(entry).is_absolute() else ROOT / entry for entry in paths]
    for path in scanner.collect_files([str(entry) for entry in resolved]):
        if scanner.is_skipped(path):
            continue
        relative = path.relative_to(ROOT).as_posix()
        if visible is not None and relative not in visible:
            continue
        if relative.startswith(NON_CODE_PREFIXES):
            continue
        if relative in state["paths"]:
            continue
        language = scanner.language_of(path)
        if language in (None, "html"):
            continue
        try:
            tokens = glossary.leitor_termos.tokens(path, language)
        except (OSError, UnicodeError):
            continue
        if not tokens:
            continue
        source = path.read_text(encoding="utf-8", errors="replace")
        starts = scanner.line_starts(source)
        cursor = 0
        hits = []
        for token in tokens:
            position = source.find(token, cursor)
            if position < 0:
                position = source.find(token)
            if position >= 0:
                cursor = position + len(token)
            if token.lower() in state["names"]:
                continue
            terms = [term for term in split_identifier(token) if term in state["dictionary"]]
            if not terms:
                continue
            roots = sorted({state["dictionary"][term] for term in terms})
            line = scanner.locate(starts, position)[0] if position >= 0 else 0
            hits.append((token, roots, line))
        if not hits:
            continue
        dirty[relative] = len(hits)
        for token, roots, line in hits:
            findings.append((relative, line, token, roots))
            seen_tokens[token] = seen_tokens.get(token, 0) + 1
    return dirty, findings, seen_tokens


def read_pending(path):
    listed = {}
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        fields = line.split("\t")
        if len(fields) != 3:
            raise ValueError(f"line {number}: expected module, count and path separated by TAB: {line!r}")
        module, count, relative = (field.strip() for field in fields)
        if not count.isdigit():
            raise ValueError(f"line {number}: invalid count: {count!r}")
        if not relative:
            raise ValueError(f"line {number}: empty path")
        if relative in listed:
            raise ValueError(f"line {number}: repeated path: {relative}")
        listed[relative] = int(count)
    return listed


def write_pending(path, dirty):
    lines = list(PENDING_HEADER)
    for relative in sorted(dirty, key=lambda item: (comments_gate.module_of(item), item)):
        lines.append(f"{comments_gate.module_of(relative)}\t{dirty[relative]}\t{relative}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def describe(finding):
    relative, line, token, roots = finding
    where = f"{relative}:{line}" if line else relative
    return f"{where}: {token} (Portuguese root: {', '.join(roots)})"


def main(argv):
    parser = argparse.ArgumentParser(
        prog="check-names.sh",
        description="CI gate: fails when a Portuguese identifier exists outside the allowlist and the pending list.",
    )
    parser.add_argument("paths", nargs="*", help="paths to check; without them, checks the repository against the pending list")
    parser.add_argument("--atualizar-pendentes", dest="update_pending", action="store_true", help="regenerates the pending list from the tree")
    parser.add_argument("--atualizar-allowlist", dest="update_allowlist", action="store_true", help="regenerates the allowlist from the published inventory")
    parser.add_argument("--measure", action="store_true", help="prints the most frequent Portuguese identifiers")
    parser.add_argument("--top", type=int, default=30, help="how many identifiers to print with --measure (default: 30)")
    parser.add_argument("--pending", default=str(PENDING_PATH), help="pending list")
    parser.add_argument("--allow-list", default=str(ALLOW_PATH), help="allowlist file")
    parser.add_argument("--root", default=str(ROOT), help="repository root")
    arguments = parser.parse_args(argv)

    actions = sum(bool(flag) for flag in (arguments.update_pending, arguments.update_allowlist, arguments.measure))
    if actions > 1:
        print("check-names: choose one of --atualizar-pendentes, --atualizar-allowlist and --measure", file=sys.stderr)
        return 2
    if actions and arguments.paths:
        print("check-names: --atualizar-pendentes, --atualizar-allowlist and --measure do not take paths", file=sys.stderr)
        return 2

    root = Path(arguments.root).resolve()
    if not root.is_dir():
        print(f"check-names: root not found: {root.as_posix()}", file=sys.stderr)
        return 2

    entries, map_errors = read_map()
    if map_errors:
        for error in map_errors[:20]:
            print(f"check-names: scripts/glossary-map.txt: {error}", file=sys.stderr)
        return 2

    allow_path = Path(arguments.allow_list)
    if not allow_path.is_absolute():
        allow_path = root / allow_path

    inventory = glossary.inventario_publicado()
    expected = generated_entries(inventory)

    if arguments.update_allowlist:
        allow_path.write_text(render_allow(list(MANUAL_ENTRIES), expected), encoding="utf-8")
        print(f"allowlist: {len(MANUAL_ENTRIES)} manual and {len(expected)} generated exception(s) written to {allow_path.as_posix()}")
        return 0

    try:
        read_allow(allow_path)
    except (OSError, ValueError) as error:
        print(f"check-names: allowlist: {error}", file=sys.stderr)
        return 2
    if allow_path.read_text(encoding="utf-8") != render_allow(list(MANUAL_ENTRIES), expected):
        print("check-names: allowlist differs from the generated one: run bash scripts/check-names.sh --atualizar-allowlist", file=sys.stderr)
        return 2

    exceptions = MANUAL_ENTRIES + tuple(expected)
    missing = [value for kind, value, _ in exceptions if kind == "path" and not (root / value).is_file()]
    if missing:
        for value in missing:
            print(f"check-names: allowlist: path exception matches no file: {value}", file=sys.stderr)
        return 2

    state = {
        "names": {value.lower() for kind, value, _ in exceptions if kind == "name"},
        "dictionary": build_dictionary(entries, {value for kind, value, _ in exceptions if kind == "term"}),
        "paths": {value for kind, value, _ in exceptions if kind == "path"},
    }

    visible = repository_paths()
    try:
        dirty, findings, seen = collect_hits(state, arguments.paths or [str(root)], visible)
    except FileNotFoundError as error:
        print(f"check-names: path not found: {error}", file=sys.stderr)
        return 2

    if arguments.measure:
        print(f"files with a Portuguese identifier: {len(dirty)}")
        print(f"identifier occurrences: {sum(dirty.values())}")
        print()
        for token, count in sorted(seen.items(), key=lambda item: (-item[1], item[0]))[: arguments.top]:
            roots = sorted({state["dictionary"][term] for term in split_identifier(token) if term in state["dictionary"]})
            print(f"{count:6d}  {token}  ({', '.join(roots)})")
        return 0

    if arguments.update_pending:
        pending_path = Path(arguments.pending)
        write_pending(pending_path, dirty)
        print(f"pendentes: {sum(dirty.values())} identifier(s) in {len(dirty)} file(s) written to {pending_path.as_posix()}")
        return 0

    if arguments.paths:
        if not findings:
            return 0
        for finding in findings:
            print(describe(finding))
        print(f"nomes: {len(findings)} Portuguese identifier(s) outside the allowlist in {len(dirty)} file(s) checked")
        return 1

    pending_path = Path(arguments.pending)
    if not pending_path.is_absolute():
        pending_path = root / pending_path
    if not pending_path.exists():
        print(f"check-names: pending list not found: {pending_path.as_posix()}", file=sys.stderr)
        print("check-names: run bash scripts/check-names.sh --atualizar-pendentes", file=sys.stderr)
        return 2
    try:
        listed = read_pending(pending_path)
    except (OSError, ValueError) as error:
        print(f"check-names: pendentes: {error}", file=sys.stderr)
        return 2

    appeared = sorted(set(dirty) - set(listed))
    vanished = sorted(set(listed) - set(dirty))
    drifted = [relative for relative in sorted(set(dirty) & set(listed)) if dirty[relative] != listed[relative]]
    if not appeared and not vanished and not drifted:
        print(f"nomes: {len(dirty)} file(s) pending as listed, no new Portuguese identifier")
        return 0

    for relative in appeared:
        print(f"+ {relative}: {dirty[relative]} Portuguese identifier(s) outside the pending list")
    for relative in vanished:
        print(f"- {relative}: listed as pending and has no Portuguese identifier left")
    for relative in drifted:
        print(f"! {relative}: the list says {listed[relative]} identifier(s) and the tree has {dirty[relative]}")
    print(
        "nomes: gate failed "
        f"({len(appeared)} new file(s), {len(vanished)} stale entr(ies), {len(drifted)} count(s) differing)"
    )
    print("nomes: run bash scripts/check-names.sh --atualizar-pendentes after renaming the module")
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
